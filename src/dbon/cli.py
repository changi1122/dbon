@cli.command("seed")
@click.argument("name")
@click.option("--rows", type=int, help="Number of rows (default: value set when the instance was created)")
@click.option("--seed", "seed_value", type=int, help="Random seed")
@_guard
def seed_cmd(name, rows, seed_value):
    """Regenerate dummy data (drops and recreates dbon_* tables)."""
    inst = _load(name)
    rows = inst.rows if rows is None else rows
    if rows <= 0:
        _fail("rows must be greater than or equal to 1")
    click.echo(f"[{name}] Loading dummy data... (rows={rows})")
    path = runner.seed(inst, rows, seed_value)
    inst.extra["seeded"] = rows
    inst.save()
    click.echo(f"Done. SQL: {path}")


@cli.command("sql")
@click.argument("name")
@click.argument("file", type=click.Path(exists=True, dir_okay=False, path_type=Path))
@click.option("--admin", is_flag=True, help="Execute using the administrator account")
@_guard
def sql_cmd(name, file, admin):
    """Execute a SQL file."""
    inst = _load(name)
    proc = runner.run_sql(inst, file.read_text(encoding="utf-8"), admin=admin)
    out = (proc.stdout + proc.stderr).strip()
    if out:
        click.echo(out)
    click.echo(f"[{name}] Executed {file.name} successfully")


@cli.command()
@click.argument("name")
@click.option("--admin", is_flag=True, help="Connect using the administrator account")
@_guard
def shell(name, admin):
    """Open a DB CLI session inside the container (sqlplus/psql/mysql/sqlcmd/csql/isql)."""
    inst = _load(name)
    spec = engines.get(inst.engine).shell(inst, admin=admin)
    sys.exit(docker.exec_interactive(inst.container, spec.cmd, user=spec.user, env=spec.env))


