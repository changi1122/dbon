def _remove(inst: Instance, keep_volume: bool) -> None:
    if inst.compose_file.exists():
        args = ["down", "--remove-orphans"] + ([] if keep_volume else ["-v"])
        docker.compose(inst.compose_file, inst.project, *args, capture=True, check=False)
    docker.run(["rm", "-f", inst.container], check=False)
    if not keep_volume:
        docker.run(["volume", "rm", "-f", inst.volume], check=False)
    instance.delete_dir(inst)


@cli.command("rm")
@click.argument("names", nargs=-1, required=True)
@click.option("-y", "--yes", is_flag=True, help="Delete without confirmation")
@click.option("--keep-volume", is_flag=True, help="Keep data volumes")
@_guard
def rm_cmd(names, yes, keep_volume):
    """Remove instances (containers, volumes, networks, and working directories)."""
    targets = [_load(n) for n in names]
    what = "container (keeping volumes)" if keep_volume else "container and data volumes"
    if not yes:
        click.confirm(f"{', '.join(names)}: Delete {what}. Continue?", abort=True)
    for inst in targets:
        _remove(inst, keep_volume)
        click.echo(f"[{inst.name}] removed")


@cli.command()
@click.option("-y", "--yes", is_flag=True, help="Delete without confirmation")
@_guard
def prune(yes):
    """Remove all instances and volumes created by dbon (based on dbon labels)."""
    insts = instance.load_all()
    containers = docker.list_by_label("container", "dbon.managed=true")
    volumes = docker.list_by_label("volume", "dbon.managed=true")
    if not (insts or containers or volumes):
        click.echo("No resources to clean up.")
        return
    click.echo(f"Instances: {', '.join(i.name for i in insts) or '-'}")
    click.echo(f"Containers: {', '.join(containers) or '-'}")
    click.echo(f"Volumes: {', '.join(volumes) or '-'}")
    if not yes:
        click.confirm("Delete all listed resources. Continue?", abort=True)
    for inst in insts:
        _remove(inst, keep_volume=False)
        click.echo(f"[{inst.name}] removed")
    for c in docker.list_by_label("container", "dbon.managed=true"):
        docker.run(["rm", "-f", c], check=False)
    for v in docker.list_by_label("volume", "dbon.managed=true"):
        docker.run(["volume", "rm", "-f", v], check=False)
    click.echo("Cleanup complete")


