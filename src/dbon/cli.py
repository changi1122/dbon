@cli.command()
@click.argument("engine_name")
@click.option("--rows", type=int, default=100, show_default=True)
@click.option("--seed", "seed_value", type=int)
@click.option("-o", "--output", type=click.Path(dir_okay=False, path_type=Path), help="Output file (default: stdout)")
@_guard
def gen(engine_name, rows, seed_value, output):
    """Generate dummy data SQL only (Docker not required)."""
    engine = engines.get(engine_name)
    sql = render(engine.dialect, rows, seed_value)
    if output:
        output.write_text(sql, encoding="utf-8")
        click.echo(f"Generated {output} ({rows} rows)", err=True)
    else:
        click.echo(sql, nl=False)


@cli.group("config")
def config_cmd() -> None:
    """Manage the shared configuration file (~/.dbon/config.yaml)."""


@config_cmd.command("path")
def config_path() -> None:
    click.echo(config.config_path())


@config_cmd.command("show")
@_guard
def config_show() -> None:
    config.init_config()
    click.echo(config.config_path().read_text(encoding="utf-8"), nl=False)


@config_cmd.command("init")
@click.option("--force", is_flag=True, help="Overwrite the existing file")
def config_init(force) -> None:
    existed = config.config_path().exists()
    path = config.init_config(force=force)
    click.echo(f"{'Already exists' if existed and not force else 'Created'}: {path}")


def main() -> None:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            try:
                stream.reconfigure(encoding="utf-8")
            except (ValueError, OSError):
                pass
    cli()


if __name__ == "__main__":
    main()
