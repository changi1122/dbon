@cli.command("ls")
@click.option("--json", "as_json", is_flag=True, help="Output in JSON format")
@_guard
def ls_cmd(as_json):
    """List instances."""
    rows = []
    for inst in instance.load_all():
        rows.append({
            "name": inst.name, "engine": inst.engine, "version": inst.version, "port": inst.port,
            "status": docker.container_status(inst.container), "user": inst.user,
            "database": engines.get(inst.engine).database_label(inst),
        })
    if as_json:
        click.echo(json.dumps(rows, indent=2, ensure_ascii=False))
        return
    if not rows:
        click.echo("No instances found. Example: dbon up mysql")
        return
    headers = ["NAME", "ENGINE", "VERSION", "PORT", "STATUS", "USER", "DATABASE"]
    table = [[str(r[k]) for k in ("name", "engine", "version", "port", "status", "user", "database")] for r in rows]
    widths = [max(len(h), *(len(row[i]) for row in table)) for i, h in enumerate(headers)]
    click.echo("  ".join(h.ljust(w) for h, w in zip(headers, widths)))
    for row in table:
        click.echo("  ".join(c.ljust(w) for c, w in zip(row, widths)))


@cli.command()
@click.argument("name")
@click.option("--json", "as_json", is_flag=True, help="Output in JSON format")
@_guard
def info(name, as_json):
    """Display connection details (account, password, JDBC URL)."""
    inst = _load(name)
    data = engines.get(inst.engine).info(inst)
    data["status"] = docker.container_status(inst.container)
    data["compose_file"] = str(inst.compose_file)
    if as_json:
        click.echo(json.dumps(data, indent=2, ensure_ascii=False))
        return
    width = max(len(k) for k in data)
    for k, v in data.items():
        click.echo(f"{k:<{width}}  {v}")


