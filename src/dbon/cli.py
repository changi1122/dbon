import click
import yaml

from dbon import config, docker, engines, instance, runner
from dbon.dummy import render
from dbon.instance import Instance

def _fail(msg: str) -> None:
    raise click.ClickException(msg)

def _load(name: str) -> Instance:
    inst = instance.load(name)
    if not inst:
        _fail(f"Instance '{name}' not found. Run `dbon ls` to check available instances.")
    return inst


def _log(msg: str) -> None:
    click.echo(msg, err=True)


def _write_compose(inst: Instance) -> None:
    engine = engines.get(inst.engine)
    inst.dir.mkdir(parents=True, exist_ok=True)
    content = yaml.safe_dump(engine.compose(inst), sort_keys=False, allow_unicode=True)
    inst.compose_file.write_text(f"# generated by dbon — do not edit by hand\n{content}", encoding="utf-8")


def _print_info(inst: Instance) -> None:
    info = engines.get(inst.engine).info(inst)
    width = max(len(k) for k in info)
    for k, v in info.items():
        click.echo(f"  {k:<{width}}  {v}") 


def _finish_setup(inst: Instance, timeout: int, rows: int, seed_value: int | None) -> None:
    """Wait for readiness, bootstrap once, and load dummy data if requested."""
    click.echo(f"Waiting for readiness... (timeout: {timeout}s)")
    pw = runner.wait_ready(inst, timeout, _log)
    if not inst.bootstrapped:
        click.echo("Creating user and database...")
        runner.bootstrap(inst, pw)
    if rows > 0 and not inst.extra.get("seeded"):
        click.echo(f"Loading dummy data... (rows={rows})")
        path = runner.seed(inst, rows, seed_value)
        inst.extra["seeded"] = rows
        inst.save()
        click.echo(f"  SQL: {path}")


def _guard(fn):
    """Turn library errors into clean CLI errors."""
    import functools

    @functools.wraps(fn)
    def wrapper(*args, **kwargs):
        try:
            return fn(*args, **kwargs)
        except (config.ConfigError, engines.EngineError, docker.DockerError, runner.RunError, ValueError, RuntimeError) as e:
            _fail(str(e))

    return wrapper


@click.group(context_settings={"help_option_names": ["-h", "--help"]})
@click.version_option(package_name="dbon")
def cli() -> None:
    """Dev/Test DBMS container management tool (oracle, postgres, mysql, mariadb, mssql, cubrid, sybase)."""


