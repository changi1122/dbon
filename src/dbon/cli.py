@cli.command("engines")
def engines_cmd() -> None:
    """List supported engines and versions."""
    for e in engines.ENGINES.values():
        versions = ", ".join(f"[{v}]" if v == e.default_version else v for v in e.versions)
        aliases = f" (aliases: {', '.join(e.aliases)})" if e.aliases else ""
        click.echo(f"{e.name:<9} {versions}  port={e.port}  admin={e.admin_user}{aliases}")
    click.echo("\n[ ] = default version. Example: dbon up mysql:8.0, dbon up pg")


