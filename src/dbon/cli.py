@cli.command()
@click.argument("name")
@click.option("--no-wait", is_flag=True, help="Skip waiting for readiness")
@_guard
def start(name, no_wait):
    """Start a stopped instance (resume incomplete initialization if needed)."""
    inst = _load(name)
    docker.compose(inst.compose_file, inst.project, "up", "-d")
    if not no_wait:
        _finish_setup(inst, inst.timeout, inst.rows, None)
    click.echo(f"[{name}] started (localhost:{inst.port})")


@cli.command()
@click.argument("names", nargs=-1, required=True)
@_guard
def stop(names):
    """Stop instances without deleting their data."""
    for name in names:
        inst = _load(name)
        docker.compose(inst.compose_file, inst.project, "stop")
        click.echo(f"[{name}] stopped")


@cli.command()
@click.argument("name")
@_guard
def restart(name):
    """Restart an instance."""
    inst = _load(name)
    docker.compose(inst.compose_file, inst.project, "restart")
    runner.wait_ready(inst, inst.timeout, _log)
    click.echo(f"[{name}] restarted")


@cli.command()
@click.argument("name")
@click.option("-f", "--follow", is_flag=True)
@click.option("--tail", default="100", show_default=True)
@_guard
def logs(name, follow, tail):
    """Display container logs."""
    inst = _load(name)
    args = ["logs", "--tail", tail] + (["-f"] if follow else [])
    docker.compose(inst.compose_file, inst.project, *args, check=False)


