@cli.command()
@click.argument("target")
@click.option("--name", help="Instance name (default: <engine><version>)")
@click.option("--port", type=int, help="Host port (default: automatically assign an available port)")
@click.option("--image", help="Specify a Docker image directly")
@click.option("--user", help="Application account")
@click.option("--password", help="Application account password")
@click.option("--admin-password", help="Administrator password")
@click.option("--database", help="Database name")
@click.option("--rows", type=int, help="Number of dummy data rows to insert (0 = skip data loading)")
@click.option("--seed", "seed_value", type=int, help="Random seed for dummy data generation")
@click.option("--mem-limit", help="Memory limit (e.g., 4g)")
@click.option("--timeout", type=int, help="Readiness timeout in seconds")
@click.option("--no-wait", is_flag=True, help="Start the container without waiting for readiness or bootstrapping (complete later with dbon start)")
@_guard
def up(target, name, port, image, user, password, admin_password, database, rows, seed_value, mem_limit, timeout, no_wait):
    """Create and start a new instance. TARGET examples: oracle, mysql:8.0, pg:16, mssql:2022, cubrid:11.4"""
    engine, version = engines.parse_target(target)
    cfg = config.load_config()
    overrides = dict(user=user, password=password, admin_password=admin_password, database=database,
                     rows=rows, mem_limit=mem_limit, timeout=timeout)
    s = config.resolve_settings(cfg, engine.name, version, overrides)

    existing = instance.load_all()
    name = name or instance.default_name(engine.name, version, [i.name for i in existing])
    instance.validate_name(name)
    if instance.load(name):
        _fail(f"Instance '{name}' already exists. Specify a different --name or run `dbon rm {name}` before trying again.")

    spec = engine.spec(version)
    ver_cfg = (((cfg.get("engines") or {}).get(engine.name) or {}).get("versions") or {}).get(version) or {}
    image = image or ver_cfg.get("image") or spec["image"]

    reserved = {i.port for i in existing}
    if port:
        if port in reserved or not instance.host_port_free(port):
            _fail(f"Port {port} is already in use")
    else:
        port = instance.allocate_port(engine.port, reserved | docker.published_host_ports())

    inst = Instance(
        name=name, engine=engine.name, version=version, image=image, port=port,
        user=s["user"], password=s["password"], admin_password=s["admin_password"], database=s["database"],
        timezone=s["timezone"], restart=s["restart"], mem_limit=s["mem_limit"], timeout=s["timeout"], rows=s["rows"],
    )
    click.echo(f"[{name}] {engine.label} {version} ({image}) → localhost:{port}")
    engine.prepare(inst)
    _write_compose(inst)
    inst.save()

    try:
        docker.compose(inst.compose_file, inst.project, "up", "-d")
    except docker.DockerError:
        _remove(inst, keep_volume=False)  # Nothing useful was created; don't leave a partially created instance.
        raise
    if no_wait:
        click.echo(f"Container started. Complete initialization later with `dbon start {name}`.")
        return
    _finish_setup(inst, inst.timeout, inst.rows, seed_value)
    click.echo(f"\n[{name}] Ready")
    _print_info(inst)



